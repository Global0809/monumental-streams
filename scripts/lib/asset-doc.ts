/**
 * Generated registries written at the end of every media build:
 *   media/art.json           studio-loop art URLs (posters, previews, LQIP) keyed by stem
 *   docs/ASSET-MANIFEST.md   human-readable inventory of every asset and studio loop
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { MediaAsset } from '../../shared/types.ts';
import { formatBytes, formatDuration, fromRoot, sizeOf, toRootRelative, writeJson } from './files.ts';
import type { MediaSource } from './media-sources.ts';
import { slugOf } from './media-sources.ts';

export interface ArtEntry {
  poster: string; // 1280w webp
  posterSmall: string; // 640w webp
  lqip: string; // data URI
  preview?: string; // 720p loop mp4
  previewSmall?: string; // 480p loop mp4
}

const PUBLIC = fromRoot('media', 'public');

/** Scans media/public/posters for "<stem>-1280.webp" and writes media/art.json. */
export async function writeArtRegistry(): Promise<Record<string, ArtEntry>> {
  const posters = path.join(PUBLIC, 'posters');
  const art: Record<string, ArtEntry> = {};
  const stems = existsSync(posters)
    ? readdirSync(posters).filter((n) => n.endsWith('-1280.webp')).map((n) => n.slice(0, -'-1280.webp'.length)).sort()
    : [];
  const has = (...p: string[]) => existsSync(path.join(PUBLIC, ...p));
  for (const stem of stems) {
    const lqipFile = path.join(posters, `${stem}-lqip.txt`);
    if (!existsSync(lqipFile)) {
      console.warn(`art: ${stem} has no ${stem}-lqip.txt — run npm run media:previews; skipped`);
      continue;
    }
    art[stem] = {
      poster: `/media/public/posters/${stem}-1280.webp`,
      posterSmall: `/media/public/posters/${stem}-${has('posters', `${stem}-640.webp`) ? 640 : 1280}.webp`,
      lqip: readFileSync(lqipFile, 'utf8').trim(),
      ...(has('previews', `${stem}-720.mp4`) ? { preview: `/media/public/previews/${stem}-720.mp4` } : {}),
      ...(has('previews', `${stem}-480.mp4`) ? { previewSmall: `/media/public/previews/${stem}-480.mp4` } : {}),
    };
  }
  await writeJson(fromRoot('media', 'art.json'), art);
  return art;
}

const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const mbps = (bps: number) => `${(bps / 1_000_000).toFixed(2)} Mb/s`;
const publicSize = (url: string | undefined) => (url ? formatBytes(sizeOf(path.join(PUBLIC, ...url.replace('/media/public/', '').split('/')))) : '—');

function provenanceCell(src: MediaSource): string {
  if (src.type === 'reel') return 'studio-concept · Monumental studio motion design (provisional); score generated in-house';
  return `${src.provenance} · ${src.licence}${src.sourceUrl ? ` · [source](${src.sourceUrl})` : ''}`;
}

function sourcesCell(src: MediaSource): string {
  if (src.type === 'file') return `\`${src.source}\`${src.trim ? ` (${src.trim.start}–${src.trim.end} s)` : ''}`;
  const repeat = src.repeat && src.repeat > 1 ? ` ×${src.repeat}` : '';
  return `${src.loops.map((s) => `\`${s}\``).join(', ')}${repeat}; score seed ${src.score.seed} (${src.score.root} ${src.score.mood})`;
}

export async function writeAssetManifestDoc(opts: {
  sources: MediaSource[];
  manifest: Record<string, MediaAsset>;
  loopFiles: Map<string, string>;
  assetBytes: (slug: string) => number;
  art: Record<string, ArtEntry>;
}): Promise<void> {
  const { sources, manifest, loopFiles, assetBytes, art } = opts;
  const built = sources.filter((s) => manifest[s.id]);
  const runtime = built.reduce((sum, s) => sum + manifest[s.id].duration, 0);
  const bytes = built.reduce((sum, s) => sum + assetBytes(slugOf(s.id)), 0);

  const lines: string[] = [
    '# Asset manifest',
    '',
    '> Generated by `scripts/build-media.ts` (`npm run media:build`). Do not edit by hand: change',
    '> `content/media-sources.json` (or the files it points to) and rebuild. Measured facts used by the',
    '> app live in `media/manifest.json`; see `docs/MEDIA.md` for how the pipeline works.',
    '',
    `**${built.length} playable asset(s)** · total runtime ${formatDuration(runtime)} · ${formatBytes(bytes)} of encoded output`,
    '',
    '## Playable assets',
    '',
    '| Media id | Title | Type | Sources | Provenance · licence | Attribution | Duration | Renditions (average bit rate) | Output |',
    '|---|---|---|---|---|---|---|---|---|',
  ];
  for (const src of sources) {
    const a = manifest[src.id];
    const attribution = src.type === 'file' ? src.attribution : 'Monumental Streams studio';
    lines.push(
      `| \`${src.id}\` | ${cell(src.title)} | ${src.type} | ${cell(sourcesCell(src))} | ${cell(provenanceCell(src))} | ${cell(attribution)} | ` +
        (a
          ? `${a.duration.toFixed(3)} s | ${a.renditions.map((r) => `${r.label} ${mbps(r.bandwidth)}`).join('<br>')} | ${formatBytes(assetBytes(slugOf(src.id)))} |`
          : 'not built | — | — |'),
    );
  }

  lines.push('', '### Files per asset', '', '| Media id | HLS master (protected) | MP4 fallback (protected) | Captions | Chapters | Thumbnails |', '|---|---|---|---|---|---|');
  for (const src of built) {
    const a = manifest[src.id];
    const slug = slugOf(src.id);
    const mp4 = fromRoot('media', 'protected', ...a.mp4.split('/'));
    const captions = a.captions.map((c) => `\`${c.src}\` (${c.lang}, ${c.kind}, ${publicSize(c.src)})`).join('<br>') || '—';
    const thumbs = a.thumbnails ? `\`${a.thumbnails}\` + sprite (${publicSize(a.thumbnails.replace(/\.vtt$/, '.webp'))})` : '—';
    lines.push(
      `| \`${src.id}\` | \`media/protected/${a.hls ?? '—'}\` (${formatBytes(sizeOf(fromRoot('media', 'protected', slug)) - sizeOf(mp4))} HLS) | ` +
        `\`media/protected/${a.mp4}\` (${formatBytes(sizeOf(mp4))}) | ${captions} | ${a.chapters ? `\`${a.chapters}\`` : '—'} | ${thumbs} |`,
    );
  }

  lines.push(
    '',
    '## Studio loops',
    '',
    'Silent, seamless 8-second 1920×1080 30 fps motion-design loops from the Monumental studio (provenance `studio-concept`,',
    'provisional until client-approved artwork replaces them). Web derivatives come from `scripts/build-previews.sh`.',
    '',
    '| Stem | Source | Preview 720 / 480 | Poster 1280 / 640 | LQIP | In art.json | Used by |',
    '|---|---|---|---|---|---|---|',
  );
  const stems = [...new Set([...loopFiles.keys(), ...Object.keys(art)])].sort();
  for (const stem of stems) {
    const source = loopFiles.get(stem);
    const size = (...p: string[]) => (existsSync(path.join(PUBLIC, ...p)) ? formatBytes(sizeOf(path.join(PUBLIC, ...p))) : 'missing');
    const usedBy = sources.filter((s) => s.type === 'reel' && s.loops.includes(stem)).map((s) => `\`${s.id}\``);
    lines.push(
      `| \`${stem}\` | ${source ? `\`${toRootRelative(source)}\` (${formatBytes(sizeOf(source))})` : 'missing'} | ` +
        `${size('previews', `${stem}-720.mp4`)} / ${size('previews', `${stem}-480.mp4`)} | ` +
        `${size('posters', `${stem}-1280.webp`)} / ${size('posters', `${stem}-640.webp`)} | ${size('posters', `${stem}-lqip.txt`)} | ` +
        `${art[stem] ? 'yes' : 'no'} | ${usedBy.join(', ') || '—'} |`,
    );
  }
  lines.push('');
  await writeFile(fromRoot('docs', 'ASSET-MANIFEST.md'), lines.join('\n'));
}
